package main

import (
	"bytes"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

// specHookMarker marks a hook file as spec-managed — a hook without it is
// foreign and is never clobbered.
const specHookMarker = "# managed by spec"

// prePushHook is the embedded hook installed into .git/hooks/pre-push
// (FEAT-036). It fails a push that changes files outside specs/ and
// .spec/ without a spec change in the same push — behavior ships with
// its spec. SPEC_SKIP=1 is the escape hatch for spec-neutral fixes.
const prePushHook = `#!/usr/bin/env bash
# managed by spec — regenerated by spec sync; do not edit by hand
# (hand edits are lost on the next sync)
#
# pre-push: behavior ships with its spec — a push that changes files
# outside specs/ and .spec/ must include a spec update in the same push,
# unless every new commit attests spec-neutrality via a
# 'Spec-Exempt: <reason>' trailer or a non-feat conventional-commit
# prefix (fix:, docs:, test:, chore:, refactor:, perf:, style:, ci:,
# build:, revert: — feat: and type!: always need the spec or trailer).
# Last-resort bypass for spec-neutral bulk changes:
#   SPEC_SKIP=1 git push

[ "${SPEC_SKIP:-0}" = "1" ] && exit 0

zero=0000000000000000000000000000000000000000
# pre-push stdin (consumed once): <local ref> <local sha> <remote ref> <remote sha>
push_updates=$(cat)
changed=$(
    printf '%s\n' "$push_updates" |
    while read -r _lref local_sha _rref remote_sha; do
        [ "$local_sha" = "$zero" ] && continue # ref deletion
        if [ "$remote_sha" = "$zero" ]; then
            # new ref: files in commits not on any remote yet
            git log --format= --name-only "$local_sha" --not --remotes
        else
            git diff --name-only "$remote_sha..$local_sha"
        fi
    done | sort -u
)

if printf '%s\n' "$changed" | grep -qEv '^$|^specs/|^\.spec/' && \
   ! printf '%s\n' "$changed" | grep -q '^specs/'; then
    # code changed, no spec in the push — allowed only when every new
    # commit attests spec-neutrality (trailer or non-feat: prefix).
    # --no-merges: a merge's content is vetted via its parent commits.
    unmarked=""
    while read -r _lref local_sha _rref remote_sha; do
        [ "$local_sha" = "$zero" ] && continue
        if [ "$remote_sha" = "$zero" ]; then
            range_commits=$(git rev-list --no-merges "$local_sha" --not --remotes)
        else
            range_commits=$(git rev-list --no-merges "$remote_sha..$local_sha")
        fi
        for sha in $range_commits; do
            git log -1 --format=%B "$sha" | grep -q '^Spec-Exempt:' && continue
            git log -1 --format=%s "$sha" | \
                grep -qE '^(fix|docs|test|chore|refactor|perf|style|ci|build|revert)(\([^)]*\))?:' || \
                unmarked="$unmarked $sha"
        done
    done <<< "$push_updates"
    if [ -n "$unmarked" ]; then
        echo "pre-push: code changed without a spec update, and these commits" >&2
        echo "          lack a 'Spec-Exempt: <reason>' trailer or non-feat: prefix:" >&2
        for sha in $unmarked; do
            echo "            $(git log -1 --format='%h %s' "$sha")" >&2
        done
        echo "          behavior ships with its spec — add or amend a spec under" >&2
        echo "          specs/ (see: spec new feature <title>), re-commit a defect" >&2
        echo "          fix with a Spec-Exempt: trailer or non-feat: prefix, or" >&2
        echo "          SPEC_SKIP=1 git push" >&2
        exit 1
    fi
fi
`

// commitMsgHook is the advisory companion to pre-push (FEAT-036): it
// warns when a commit changes files outside specs/ and .spec/ without a
// specs/ change or a 'Spec-Exempt:' trailer — the early nudge; pre-push
// stays the enforcement point. It never blocks (always exits 0).
const commitMsgHook = `#!/usr/bin/env bash
# managed by spec — regenerated by spec sync; do not edit by hand
# (hand edits are lost on the next sync)
#
# commit-msg: advisory only — warn when a commit changes files outside
# specs/ and .spec/ with no specs/ change, 'Spec-Exempt:' trailer, or
# non-feat: prefix in the message. Enforcement is the pre-push hook;
# this is the early nudge.

changed=$(git diff --cached --name-only)
if printf '%s\n' "$changed" | grep -qEv '^$|^specs/|^\.spec/' && \
   ! printf '%s\n' "$changed" | grep -q '^specs/' && \
   ! grep -q '^Spec-Exempt:' "$1" && \
   ! head -1 "$1" | grep -qE '^(fix|docs|test|chore|refactor|perf|style|ci|build|revert)(\([^)]*\))?:'; then
    echo "note: no specs/ change, Spec-Exempt trailer, or non-feat: prefix in" >&2
    echo "      this commit — the pre-push hook will reject the push unless a later" >&2
    echo "      commit adds one (see: spec new feature, or spec commit --exempt)." >&2
fi
exit 0
`

// preCommitHook gates plain `git commit` on the repo's pre_commit:
// checks (FEAT-041) — the hook `spec commit` already runs for its own
// path. It execs `spec precheck` rather than duplicating config parsing.
// A missing spec binary warns and passes: the enforced path is `spec
// commit`, and a missing tool must not brick commits.
const preCommitHook = `#!/usr/bin/env bash
# managed by spec — regenerated by spec sync; do not edit by hand
# (hand edits are lost on the next sync)
#
# pre-commit: runs the repo's pre_commit: checks from .spec/config.yml
# via 'spec precheck' (FEAT-041). A missing spec binary warns and
# passes — 'spec commit' is the enforced path.
# Last-resort bypass for a stuck check: SPEC_SKIP=1 git commit

[ "${SPEC_SKIP:-0}" = "1" ] && exit 0

command -v spec >/dev/null 2>&1 || {
    echo "note: spec not on PATH — skipping pre_commit checks" >&2
    exit 0
}
# version-tolerant: an installed binary older than the precheck command
# must not block commits — only binaries that know the command gate
spec help 2>/dev/null | grep -q 'spec precheck' || {
    echo "note: installed spec predates 'precheck' — skipping pre_commit checks" >&2
    exit 0
}
spec precheck
`

// specHookScripts is every hook spec manages, in install order.
var specHookScripts = []struct{ name, script string }{
	{"pre-commit", preCommitHook},
	{"commit-msg", commitMsgHook},
	{"pre-push", prePushHook},
}

// gitHooksDir resolves the repo's hooks dir via git (worktree-aware).
func gitHooksDir(root string) (string, bool) {
	cmd := exec.Command("git", "rev-parse", "--git-path", "hooks")
	cmd.Dir = root
	b, err := cmd.Output()
	if err != nil {
		return "", false
	}
	dir := strings.TrimSpace(string(b))
	if !filepath.IsAbs(dir) {
		dir = filepath.Join(root, dir)
	}
	return dir, true
}

// hookFileState reports one hook's state: "installed", "outdated",
// "missing", or "foreign".
func hookFileState(dir, name, want string) string {
	data, err := os.ReadFile(filepath.Join(dir, name))
	switch {
	case os.IsNotExist(err):
		return "missing"
	case err != nil:
		return ""
	case !bytes.Contains(data, []byte(specHookMarker)):
		return "foreign"
	case !bytes.Equal(data, []byte(want)):
		return "outdated"
	default:
		return "installed"
	}
}

// specHooksSummary reports all managed hooks for `spec status`:
// "pre-push: installed, commit-msg: missing" — "" outside git repos.
func specHooksSummary(root string) string {
	dir, ok := gitHooksDir(root)
	if !ok {
		return ""
	}
	var parts []string
	fix := false
	for _, h := range specHookScripts {
		s := hookFileState(dir, h.name, h.script)
		if s == "foreign" {
			s = "foreign (unmanaged)"
		}
		if s != "installed" {
			fix = true
		}
		parts = append(parts, h.name+": "+s)
	}
	line := strings.Join(parts, ", ")
	if fix {
		line += " — 'spec skill sync' installs/refreshes"
	}
	return line
}

// ensureSpecHooks installs the managed hooks (.git/hooks/pre-push and
// commit-msg) so every spec-managed repo gets spec-coverage enforcement
// and the advisory nudge. Foreign hooks are left alone with a note;
// stale managed hooks refresh. Silent no-op where git or a repo is absent.
func ensureSpecHooks(root string, out io.Writer) {
	hooksDir, ok := gitHooksDir(root)
	if !ok {
		return
	}
	for _, h := range specHookScripts {
		hookPath := filepath.Join(hooksDir, h.name)
		data, err := os.ReadFile(hookPath)
		switch {
		case err == nil && !bytes.Contains(data, []byte(specHookMarker)):
			fmt.Fprintf(out, "note: %s is a foreign %s hook — left alone\n", hookPath, h.name)
			continue
		case err == nil && bytes.Equal(data, []byte(h.script)):
			continue // current
		case err != nil && !os.IsNotExist(err):
			continue
		}
		if err := os.MkdirAll(filepath.Dir(hookPath), 0o755); err != nil {
			continue
		}
		if err := os.WriteFile(hookPath, []byte(h.script), 0o755); err == nil {
			fmt.Fprintf(out, "installed %s\n", hookPath)
		}
	}
}
